//go:build unix

package harness

import (
	"os/exec"
	"syscall"
)

// setProcessGroup gives the harness its own process group, which is
// terminated as a whole on cancel: harnesses are often wrapper scripts and
// spawn MCP servers which would otherwise outlive them.
func setProcessGroup(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		return syscall.Kill(-cmd.Process.Pid, syscall.SIGTERM)
	}
}
